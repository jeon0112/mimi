@dataclass(frozen=True)
class SajuLines:
    """효 여섯. **전부 이진이다** — 재료가 본래 이진이기 때문이다 (E-115).

    이름이 「무엇을 쟀나」를 그대로 말한다. `line1` 같은 이름을 쓰지 않는다 —
    나중에 어느 효가 무엇이었는지 코드만 보고 알 수 있어야 한다.
    """
    ilgan_yang: bool        # 초효 · 일간 음양      (갑병무경임 = True)
    singang: bool           # 2효  · 신강신약       (신강 = True)
    month_warm: bool        # 3효  · 월지 계절      (봄여름 = True)
    daeun_forward: bool     # 4효  · 대운 순역      (순행 = True)
    cheoneul: bool          # 5효  · 천을귀인       (든다 = True)
    daeun_branch_yang: bool # 상효 · 대운지지 음양   (자인진오신술 = True)

    def lower(self) -> str:
        """하괘 — 안 · 몸 · 나 · 타고난 것"""
        return TRIGRAM_BY_LINES[(self.ilgan_yang, self.singang, self.month_warm)]

    def upper(self) -> str:
        """상괘 — 밖 · 환경 · 남 · 오는 것"""
        return TRIGRAM_BY_LINES[
            (self.daeun_forward, self.cheoneul, self.daeun_branch_yang)]

    def trigrams(self) -> str:
        """`iching_data.json` 과 같은 표기 — **상괘가 앞이다** (E-338)"""
        return f"{self.upper()}/{self.lower()}"


@dataclass(frozen=True)
class Match:
    trigrams: str
    number: int | None      # ★ 데이터에 없으면 None. 가까운 괘로 대신하지 않는다
    covered: bool
    path: str = "조합"      # ★ 어느 경로가 이 괘를 냈나 — 뭉클이 제안 (E-463)
    #
    # ★★★★★ 왜 표시를 남기나
    #   컨텍스트 경로가 받은 판과 조합 경로가 받은 판이 섞이면
    #   「조합 덮임 71.7%」와 「컨텍스트 비중」을 따로 셀 수 없다.
    #   그러면 두 숫자가 한 문장에 섞여 읽히고, 그것이 E-144 였다.
    #   ★★ 어제 배운 E-448(덮임에 두 수가 있고 섞으면 안 된다)과 같은 줄이다.


def match(lines: SajuLines, available: set[int]) -> Match:
    """효 여섯 → 괘.

    `available` 은 **지금 데이터에 글이 있는 괘 번호들**이고 **필수다.**

    ★★★★★ 기본값을 두지 않는다. 예전에는 `KNOWN` 을 기본값으로 썼는데,
      **데이터가 늘어도 그 표는 안 늘어서 조용히 옛 숫자가 나왔다**(E-488).
      **부르는 쪽이 「지금 무엇이 있나」를 대야 한다.**

    ★ 조합은 64가지가 다 나오지만, **글이 있는 것만 covered 다.**
      없는 자리를 가까운 괘로 메우지 않는다 — 그러면 덮임 숫자가 거짓말이 된다.
    """
    t = lines.trigrams()
    n = NUMBER_BY_TRIGRAMS[t]          # 조합은 반드시 64 중 하나다
    return Match(trigrams=t, number=n if n in available else None,
                 covered=n in available)


def coverage(available: set[int]) -> dict:
    """조합 64 중 몇 개가 글을 가졌나. **덮임의 정직한 정의다.**

    `available` 은 **필수다** — 이유는 `match()` 와 같다(E-488).
    ★★ **데이터 파일에서 읽어 넘겨라.** 손으로 적은 표를 넘기면 그 표가 낡는다.

    ★ 이것은 「조합 기준」이다. 사람 기준 덮임(240판 중 몇 판)은 **다른 수**이고,
      그건 실제 명식 분포를 돌려야 나온다 (E-409: 42.5% = 102판/240판).
    """
    have = available
    covered = sorted(n for n in HEXAGRAM_TRIGRAMS if n in have)
    return {
        "총_조합": 64,
        "글이_있는_조합": len(covered),
        "덮임": round(len(covered) / 64 * 100, 1),
        "빈_조합": [HEXAGRAM_TRIGRAMS[n] for n in HEXAGRAM_TRIGRAMS
                    if n not in have],
    }
